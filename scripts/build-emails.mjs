/**
 * Compile the MJML email templates to HTML.
 *
 * The app renders emails by substituting {{vars}} into this precompiled HTML, so
 * neither mjml nor the template files are needed at runtime (Cloudflare Workers
 * has no filesystem, and mjml is heavy).
 *
 * Usage:
 *   npm run email:build   # rewrite src/emails/compiled.ts
 *   npm run email:check   # fail if src/emails/compiled.ts is out of date
 *
 * Run email:build after editing anything in src/emails/templates or src/emails/partials.
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import mjml from "mjml";

const EMAILS_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/emails");
const TEMPLATES_DIR = path.join(EMAILS_DIR, "templates");
const PARTIALS_DIR = path.join(EMAILS_DIR, "partials");
export const COMPILED_PATH = path.join(EMAILS_DIR, "compiled.ts");

const VAR_PATTERN = /\{\{(\w+)\}\}/g;

function varsIn(source) {
  return [...new Set([...source.matchAll(VAR_PATTERN)].map((m) => m[1]))].sort();
}

async function compileTemplate(name) {
  const source = await readFile(path.join(TEMPLATES_DIR, `${name}.mjml`), "utf8");
  const { html, errors } = await mjml(source, {
    ignoreIncludes: false,
    filePath: TEMPLATES_DIR,
    includePath: PARTIALS_DIR,
    validationLevel: "soft",
  });

  const fatalErrors = errors.filter((error) => error.level === "error");
  if (fatalErrors.length > 0) {
    const message = fatalErrors.map((error) => error.formattedMessage || error.message).join("\n");
    throw new Error(`Failed to compile email template "${name}":\n${message}`);
  }

  // Vars are substituted after compiling, so mjml must pass every placeholder through untouched.
  const expected = varsIn(source).join(", ");
  const actual = varsIn(html).join(", ");
  if (expected !== actual) {
    throw new Error(`Email template "${name}" lost placeholders while compiling: expected [${expected}], got [${actual}]`);
  }

  return html;
}

/** Source of src/emails/compiled.ts for the current templates. */
export async function buildCompiledModule() {
  const names = (await readdir(TEMPLATES_DIR))
    .filter((file) => file.endsWith(".mjml"))
    .map((file) => file.slice(0, -".mjml".length))
    .sort();

  const entries = [];
  for (const name of names) {
    entries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(await compileTemplate(name))},`);
  }

  return [
    "// Generated by scripts/build-emails.mjs from src/emails/templates. Do not edit.",
    "// Run `npm run email:build` after changing a template or partial.",
    "",
    "export const compiledTemplates = {",
    ...entries,
    "} as const;",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = await buildCompiledModule();
  if (process.argv.includes("--check")) {
    const current = await readFile(COMPILED_PATH, "utf8").catch(() => "");
    if (current !== next) {
      console.error("src/emails/compiled.ts is out of date. Run `npm run email:build`.");
      process.exit(1);
    }
  } else {
    await writeFile(COMPILED_PATH, next);
    console.log(`Wrote ${path.relative(process.cwd(), COMPILED_PATH)}`);
  }
}
